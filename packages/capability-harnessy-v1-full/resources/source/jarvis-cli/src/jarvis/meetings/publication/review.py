def _item_page(service: PublicationService, item_id: str, token: str) -> str:
    item = service.store.get(item_id)
    if item is None:
        return _message_page("Not found", "That meeting is not in the local queue.")
    try:
        note = service.load_live_note(item_id)
    except (OSError, UnicodeError, ValueError) as exc:
        return _message_page("Cannot read note", html.escape(str(exc)))
    if note.source_hash != item.source_hash:
        service.store.upsert_note(note)
        return _message_page(
            "Meeting changed",
            "The note changed on disk. Return to the inbox to review the latest version.",
        )
    csrf = _csrf(token)
    summary = discord_purpose_for_publication(
        note,
        summary_override=item.discord_summary_override,
    )
    summary_editor = (
        f"""<label class="discord-editor-label" for="discord-summary">
          Discord purpose sentence
        </label>
        <textarea class="discord-summary" id="discord-summary"
          name="discord_summary" form="approve-form"
          maxlength="{DISCORD_PURPOSE_MAX_LENGTH}" required
          aria-describedby="discord-summary-help"
          spellcheck="true">{html.escape(summary)}</textarea>
        <p class="discord-editor-help" id="discord-summary-help">
          Keep this to one short sentence. It does not alter the meeting note.
        </p>"""
        if item.status == PublicationStatus.PENDING_REVIEW
        else f'<div class="discord-summary-static">{html.escape(summary)}</div>'
    )
    actions: str
    if item.status == PublicationStatus.PENDING_REVIEW:
        actions = f"""
        <section class="card action-card">
          <p class="section-label">Decision</p>
          <h2>Ready to publish?</h2>
          <p>Approval applies only to this exact version of the note.</p>
          <div class="actions">
          <form id="approve-form" method="post" action="/approve/{item.item_id}">
            <input type="hidden" name="csrf" value="{csrf}">
            <button class="approve" type="submit">Approve &amp; publish</button>
            <button class="save-note" type="submit"
              formaction="/update-note/{item.item_id}">Update meeting note</button>
          </form>
          <form method="post" action="/reject/{item.item_id}">
            <input type="hidden" name="csrf" value="{csrf}">
            <button class="reject" type="submit">Reject</button>
          </form>
          </div>
          <p class="privacy-note">
            Updating writes the canonical local Markdown and keeps this meeting unapproved.
          </p>
        </section>
        """
    else:
        actions = f"""
        <section class="card action-card">
          <p class="section-label">Decision</p>
          <h2>{_status_label(item.status)}</h2>
          <p>This meeting is no longer awaiting review.</p>
        </section>
        """
    metadata_markdown, note_markdown = _split_note_markdown(note.markdown)
    metadata = (
        f"""<details class="metadata-card">
          <summary>Meeting metadata</summary>
          <div class="markdown-body metadata-body">{_render_markdown(metadata_markdown)}</div>
        </details>"""
        if metadata_markdown
        else ""
    )
    note_editor = (
        f"""<label class="meeting-editor-label" for="meeting-markdown">
          Edit meeting note Markdown
        </label>
        <textarea class="meeting-note-editor" id="meeting-markdown"
          name="meeting_markdown" form="approve-form"
          maxlength="{MEETING_NOTE_MAX_LENGTH}" required
          aria-describedby="meeting-markdown-help"
          spellcheck="true">{html.escape(note.markdown)}</textarea>
        <p class="meeting-editor-help" id="meeting-markdown-help">
          Update meeting note writes this canonical file locally but does not approve or publish it.
        </p>"""
        if item.status == PublicationStatus.PENDING_REVIEW
        else ""
    )
    body = f"""
      <a class="back-link" href="/"><span aria-hidden="true">←</span> Review inbox</a>
      <header class="meeting-header">
        <p class="eyebrow">Flow Research · Meeting review</p>
        <h1>{html.escape(note.title)}</h1>
        <div class="meta-row">
          <span class="meta-pill">{_format_date(note.meeting_date)}</span>
          <span class="meta-pill">Flow</span>
          <span class="status-pill status-{item.status.value}">{_status_label(item.status)}</span>
        </div>
      </header>
      <div class="review-grid">
        <main class="card note-card">
          <div class="section-heading">
            <div><p class="section-label">Canonical source</p><h2>Meeting note</h2></div>
            <span class="local-badge">Local Markdown</span>
          </div>
          {metadata}
          <article class="markdown-body meeting-note">{_render_markdown(note_markdown)}</article>
          {note_editor}
        </main>
        <aside class="review-sidebar">
          <section class="card preview-card">
            <div class="section-heading preview-heading">
              <div><p class="section-label">Destination preview</p><h2>Discord</h2></div>
              <span class="summary-badge">Summary only</span>
            </div>
            <div class="discord-shell">
              <div class="discord-avatar" aria-hidden="true">F</div>
              <div class="discord-message">
                <div class="discord-author">Flow Research <span>BOT</span></div>
                <div class="discord-title">{html.escape(note.title)}</div>
                <div class="discord-date">{note.meeting_date.isoformat()} · Flow</div>
                {summary_editor}
                <div class="discord-doc-link">↗ Read the full meeting notes</div>
              </div>
            </div>
          </section>
          {actions}
        </aside>
      </div>
    """
    return _page(note.title, body)


def _csrf(token: str) -> str:
    return hashlib.sha256(f"meeting-review:{token}".encode()).hexdigest()


def _render_markdown(markdown: str) -> str:
    """Render untrusted meeting Markdown without allowing embedded HTML."""

    renderer = MarkdownIt(
        "commonmark",
        {"html": False, "linkify": False, "typographer": False},
    )
    rendered = str(renderer.render(markdown))
    return rendered.replace("<a href=", '<a target="_blank" rel="noopener noreferrer" href=')


def _split_note_markdown(markdown: str) -> tuple[str, str]:
    """Separate noisy metadata and the duplicate title from the readable note."""

    lines = markdown.splitlines()
    while lines and not lines[0].strip():
        lines.pop(0)
    if lines and lines[0].startswith("# "):
        lines.pop(0)
    while lines and not lines[0].strip():
        lines.pop(0)

    metadata: list[str] = []
    note: list[str] = []
    in_metadata = False
    for line in lines:
        if line.strip().lower() == "## metadata":
            in_metadata = True
            continue
        if in_metadata and line.startswith("## "):
            in_metadata = False
        if in_metadata:
            metadata.append(line)
        else:
            note.append(line)
    return "\n".join(metadata).strip(), "\n".join(note).strip()


def _format_date(value: date) -> str:
    return f"{value:%B} {value.day}, {value.year}"


def _status_label(status: PublicationStatus) -> str:
    return status.value.replace("_", " ").title()


def _message_page(title: str, message: str) -> str:
    return _page(
        title,
        f"""<section class="card message-card"><p class="eyebrow">Publication review</p>
        <h1>{html.escape(title)}</h1><p>{message}</p>
        <a class="button primary-button" href="/">Return to inbox</a></section>""",
    )


