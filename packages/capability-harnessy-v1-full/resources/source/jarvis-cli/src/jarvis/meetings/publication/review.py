_COOKIE_NAME = "jarvis_meeting_review"
_MAX_REVIEW_FORM_BYTES = 1_000_000


def create_review_server(
    service: PublicationService,
    briefing_service: CommunityBriefingService | None = None,
) -> ThreadingHTTPServer:
    """Create a loopback-only server; callers control its lifecycle."""

    token = review_token(service.state_root)
    handler = _handler_class(service, token, briefing_service)
    return ThreadingHTTPServer((service.config.review_host, service.config.review_port), handler)


def serve_review(
    service: PublicationService,
    briefing_service: CommunityBriefingService | None = None,
) -> None:
    """Run the local review inbox until interrupted."""

    server = create_review_server(service, briefing_service)
    try:
        server.serve_forever()
    finally:
        server.server_close()


def _handler_class(
    service: PublicationService,
    token: str,
    briefing_service: CommunityBriefingService | None,
) -> type[BaseHTTPRequestHandler]:
    class ReviewHandler(BaseHTTPRequestHandler):
        server_version = "JarvisMeetingReview/1"

        def log_message(self, format: str, *args: object) -> None:
            return

        def do_GET(self) -> None:  # noqa: N802
            parsed = urllib.parse.urlsplit(self.path)
            query = urllib.parse.parse_qs(parsed.query)
            supplied = query.get("token", [""])[0]
            authenticated = self._cookie_token_valid() or hmac.compare_digest(supplied, token)
            if not authenticated:
                self._write(
                    HTTPStatus.UNAUTHORIZED,
                    _message_page("Unauthorized", "Use the local review link generated by Jarvis."),
                )
                return
            headers = {}
            if supplied:
                headers["Set-Cookie"] = f"{_COOKIE_NAME}={token}; HttpOnly; SameSite=Strict; Path=/"
            if parsed.path == "/":
                self._write(
                    HTTPStatus.OK,
                    _inbox_page(service, token, briefing_service),
                    headers=headers,
                )
                return
            if parsed.path.startswith("/briefing/") and briefing_service is not None:
                briefing_id = parsed.path.removeprefix("/briefing/").strip("/")
                self._write(
                    HTTPStatus.OK,
                    _briefing_page(briefing_service, briefing_id, token),
                    headers=headers,
                )
                return
            if parsed.path.startswith("/item/"):
                item_id = parsed.path.removeprefix("/item/").strip("/")
                self._write(HTTPStatus.OK, _item_page(service, item_id, token), headers=headers)
                return
            self._write(HTTPStatus.NOT_FOUND, _message_page("Not found", "Unknown review page."))

        def do_POST(self) -> None:  # noqa: N802
            if not self._cookie_token_valid():
                self._write(
                    HTTPStatus.UNAUTHORIZED,
                    _message_page("Unauthorized", "Reload the authenticated local review link."),
                )
                return
            try:
                length = min(
                    int(self.headers.get("Content-Length", "0")),
                    _MAX_REVIEW_FORM_BYTES,
                )
            except ValueError:
                length = 0
            form = urllib.parse.parse_qs(self.rfile.read(length).decode("utf-8", errors="replace"))
            supplied = form.get("csrf", [""])[0]
            if not hmac.compare_digest(supplied, _csrf(token)):
                self._write(
                    HTTPStatus.FORBIDDEN,
                    _message_page("Forbidden", "The review form expired. Reload it and try again."),
                )
                return
            path = urllib.parse.urlsplit(self.path).path
            try:
                if path.startswith("/briefing/save/") and briefing_service is not None:
                    briefing_service.save_draft(
                        path.removeprefix("/briefing/save/").strip("/"),
                        markdown=form.get("briefing_markdown", [""])[0],
                        discord_summary=form.get("discord_summary", [""])[0],
                    )
                    destination = path.removeprefix("/briefing/save/").strip("/")
                    self.send_response(HTTPStatus.SEE_OTHER)
                    self.send_header("Location", f"/briefing/{destination}")
                    self.end_headers()
                    return
                if path.startswith("/update-note/"):
                    destination = path.removeprefix("/update-note/").strip("/")
                    service.update_note(
                        destination,
                        markdown=form.get("meeting_markdown", [""])[0],
                    )
                    self.send_response(HTTPStatus.SEE_OTHER)
                    self.send_header("Location", f"/item/{destination}")
                    self.end_headers()
                    return
                if path.startswith("/briefing/approve/") and briefing_service is not None:
                    briefing_service.approve(
                        path.removeprefix("/briefing/approve/").strip("/"),
                        markdown=form.get("briefing_markdown", [""])[0],
                        discord_summary=form.get("discord_summary", [""])[0],
                    )
                elif path.startswith("/briefing/reject/") and briefing_service is not None:
                    briefing_service.reject(path.removeprefix("/briefing/reject/").strip("/"))
                elif path.startswith("/approve/"):
                    reviewed_summary = form.get("discord_summary")
                    meeting_markdown = form.get("meeting_markdown")
                    service.approve(
                        path.removeprefix("/approve/").strip("/"),
                        meeting_markdown=(meeting_markdown[0] if meeting_markdown else None),
                        discord_summary=reviewed_summary[0] if reviewed_summary else None,
                    )
                elif path.startswith("/reject/"):
                    service.reject(path.removeprefix("/reject/").strip("/"))
                else:
                    self._write(
                        HTTPStatus.NOT_FOUND, _message_page("Not found", "Unknown review action.")
                    )
                    return
            except (KeyError, OSError, UnicodeError, ValueError) as exc:
                self._write(
                    HTTPStatus.CONFLICT, _message_page("Review changed", html.escape(str(exc)))
                )
                return
            self.send_response(HTTPStatus.SEE_OTHER)
            self.send_header("Location", "/")
            self.end_headers()

        def _cookie_token_valid(self) -> bool:
            cookie = SimpleCookie()
            cookie.load(self.headers.get("Cookie", ""))
            morsel = cookie.get(_COOKIE_NAME)
            return bool(morsel and hmac.compare_digest(morsel.value, token))

        def _write(
            self,
            status: HTTPStatus,
            body: str,
            *,
            headers: dict[str, str] | None = None,
        ) -> None:
            encoded = body.encode("utf-8")
            self.send_response(status)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(encoded)))
            self.send_header("Cache-Control", "no-store")
            self.send_header(
                "Content-Security-Policy",
                "default-src 'none'; style-src 'unsafe-inline'; "
                "form-action 'self'; base-uri 'none'; frame-ancestors 'none'",
            )
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("Referrer-Policy", "no-referrer")
            for key, value in (headers or {}).items():
                self.send_header(key, value)
            self.end_headers()
            self.wfile.write(encoded)

    return ReviewHandler


def _inbox_page(
    service: PublicationService,
    token: str,
    briefing_service: CommunityBriefingService | None = None,
) -> str:
    pending = service.store.list_items(PublicationStatus.PENDING_REVIEW)
    blocked = service.store.list_items(PublicationStatus.BLOCKED)
    counts = service.store.counts()
    briefing_pending = (
        briefing_service.store.list_items(PublicationStatus.PENDING_REVIEW)
        if briefing_service is not None
        else []
    )
    if pending:
        item = pending[0]
        body = f"""
        <header class="page-intro">
          <p class="eyebrow">Flow Research · Publication queue</p>
          <div class="intro-row">
            <div>
              <h1>Publication review</h1>
              <p class="lede">Review weekly briefings and meetings before anything is published.</p>
            </div>
            <span class="count-badge">{len(pending)} waiting</span>
          </div>
        </header>
        <section class="card queue-card">
          <p class="section-label">Next meeting</p>
          <h2>{html.escape(item.title)}</h2>
          <div class="meta-row">
            <span class="meta-pill">{_format_date(item.meeting_date)}</span>
            <span class="meta-pill">Flow</span>
            <span class="status-pill status-{item.status.value}">{_status_label(item.status)}</span>
          </div>
          <a class="button primary-button" href="/item/{item.item_id}">
            Review meeting <span aria-hidden="true">→</span>
          </a>
        </section>
        """
    else:
        lede = (
            "A weekly briefing is waiting below. No meetings need review."
            if briefing_pending
            else "Everything has been reviewed. New publications will appear here automatically."
        )
        body = f"""
        <header class="page-intro">
          <p class="eyebrow">Flow Research · Publication queue</p>
          <h1>Publication review</h1>
          <p class="lede">{lede}</p>
        </header>
        <section class="card empty-card"><div class="empty-icon">✓</div><h2>Queue clear</h2>
        <p>No meetings are waiting for review.</p></section>
        """
    if briefing_service is not None:
        briefing_blocked = briefing_service.store.list_items(PublicationStatus.BLOCKED)
        if briefing_pending:
            briefing = briefing_pending[0]
            briefing_range = f"{briefing.week_start.isoformat()} to {briefing.week_end.isoformat()}"
            briefing_status = _status_label(briefing.status)
            briefing_card = f"""
            <section class="card queue-card">
              <p class="section-label">Weekly community briefing</p>
              <h2>Week of {_format_date(briefing.week_start)}</h2>
              <div class="meta-row">
                <span class="meta-pill">{briefing_range}</span>
                <span class="status-pill status-{briefing.status.value}">{briefing_status}</span>
              </div>
              <a class="button primary-button" href="/briefing/{briefing.briefing_id}">
                Review briefing <span aria-hidden="true">→</span>
              </a>
            </section>
            """
            body = body.replace("</header>", "</header>" + briefing_card, 1)
        if briefing_blocked:
            body += (
                '<section class="card attention-card"><p class="section-label">'
                "Weekly briefing needs attention</p><ul>"
            )
            body += "".join(
                f"<li>Week of {_format_date(item.week_start)} — "
                f"{html.escape(item.error_message or 'Configuration error')}</li>"
                for item in briefing_blocked
            )
            body += "</ul></section>"
        briefing_counts = briefing_service.store.counts()
        body += (
            '<details class="card queue-status"><summary>Weekly briefing status</summary>'
            '<div class="status-grid">'
            + "".join(
                "<div><span>"
                f"{html.escape(key.replace('_', ' ').title())}"
                f"</span><strong>{value}</strong></div>"
                for key, value in briefing_counts.items()
            )
            + "</div></details>"
        )
    if blocked:
        body += (
            '<section class="card attention-card"><p class="section-label">Needs attention</p><ul>'
        )
        body += "".join(
            f"<li>{html.escape(item.title)} — "
            f"{html.escape(item.error_message or 'Configuration error')}</li>"
            for item in blocked
        )
        body += "</ul></section>"
    body += (
        '<details class="card queue-status"><summary>Queue status</summary>'
        '<div class="status-grid">'
        + "".join(
            "<div><span>"
            f"{html.escape(key.replace('_', ' ').title())}"
            f"</span><strong>{value}</strong></div>"
            for key, value in counts.items()
        )
        + "</div></details>"
    )
    return _page("Publication review", body)


